    final birthTzolkin = birthMayaDate['tzolkin']!;
    final birthDaySign = birthTzolkin.split(' ')[1];

    // 相性の計算
    final compatibility = _calculateCompatibility(daySign, birthDaySign);

    // ラッキーな方角を選択
    final luckyDirections = _getRandomDirections(date);

    // 運勢テキストを選択
    final fortuneText = _getRandomFortuneText(energyLevel, date);

    // アドバイスを選択
    final advice = _getRandomAdvice(daySign, luckyDirections, date);

    return DailyFortune(
      date: date,
      energyLevel: energyLevel,
      daySign: daySign,
      fortuneText: fortuneText,
      luckyDirections: luckyDirections,
      compatibility: compatibility,
      advice: advice,
    );
  }

  static String _calculateCompatibility(
      String currentDaySign, String birthDaySign) {
    // より詳細な相性計算
    final compatibilityLevels = {
      '最高': ['イミシュ-カン', 'イク-チッチャン', 'アクバル-キミ', 'カン-チッチャン', 'チッチャン-キミ'],
      '良好': ['キミ-マニク', 'マニク-ラマト', 'ラマト-ムルク', 'ムルク-オク', 'オク-チュエン'],
      '普通': ['チュエン-エブ', 'エブ-ベン', 'ベン-イシュ', 'イシュ-メン', 'メン-キブ'],
      '要注意': ['キブ-カバン', 'カバン-エツナブ', 'エツナブ-カウアク', 'カウアク-アハウ', 'アハウ-イミシュ'],
    };

    // 相性の判定（日付による変動を削除）
    return _getBaseCompatibility(
        currentDaySign, birthDaySign, compatibilityLevels);
  }

  static String _getBaseCompatibility(String currentDaySign,
      String birthDaySign, Map<String, List<String>> compatibilityLevels) {
    for (final entry in compatibilityLevels.entries) {
      for (final pair in entry.value) {
        final signs = pair.split('-');
        if ((signs[0] == currentDaySign && signs[1] == birthDaySign) ||
            (signs[1] == currentDaySign && signs[0] == birthDaySign)) {
          return entry.key;
        }
      }
    }
    return '普通';
  }

  static List<String> _getRandomDirections(DateTime date) {
    // 日付をシードとして使用
    final seed = date.year * 10000 + date.month * 100 + date.day;

    // シードに基づいてシャッフル
    final List<String> shuffled = List.from(_directions);
    for (int i = shuffled.length - 1; i > 0; i--) {
      final j = (seed + i) % (i + 1);
      final temp = shuffled[i];
      shuffled[i] = shuffled[j];
      shuffled[j] = temp;
    }

    // 2つの異なる方角を選択
    final firstIndex = seed % shuffled.length;
    var secondIndex = (seed + 7) % shuffled.length;
    if (secondIndex == firstIndex) {
      secondIndex = (secondIndex + 1) % shuffled.length;
    }

    return [shuffled[firstIndex], shuffled[secondIndex]];
  }

  static String _getRandomFortuneText(String energyLevel, DateTime date) {
    final texts = _energyFortuneTexts[energyLevel] ?? _energyFortuneTexts['1']!;
    // 日付をシードとして使用（1-365の範囲に変換）
    final dayOfYear = date.difference(DateTime(date.year, 1, 1)).inDays + 1;
    return texts[dayOfYear % texts.length];
  }

  static String _getRandomAdvice(
      String daySign, List<String> directions, DateTime date) {
    final daySignAdvices = _daySignAdvice[daySign] ?? _daySignAdvice['イミシュ']!;
    final directionActions =
        _directionActions[directions[0]] ?? _directionActions['東']!;

    // 日付をシードとして使用
    final seed = date.year * 10000 + date.month * 100 + date.day;

    // アドバイスとアクションの選択に異なるオフセットを使用
    final daySignAdvice =
        daySignAdvices[(seed + daySign.hashCode) % daySignAdvices.length];
    final directionAction = directionActions[
        (seed + directions[0].hashCode) % directionActions.length];

    return '$daySignAdvice\n特に、$directionActionと良いでしょう。';
  }
